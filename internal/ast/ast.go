func (*ErrorSetDecl) declNode() {}

// String returns a compact debug representation of the error set declaration.
func (d *ErrorSetDecl) String() string {
	prefix := ""
	if d.Public {
		prefix = "pub "
	}
	return fmt.Sprintf("%serror %s { %s }", prefix, d.Name, strings.Join(d.Members, ", "))
}

