// Position identifies a source position using one-based line and column values.
type Position struct {
	Line   int
	Column int
}

// Span identifies a half-open source range using one-based positions.
//
// File is the path the range was read from. A package is checked as one merged
// program, so without it a diagnostic's line and column say nothing about which
// module they belong to.
type Span struct {
	File  string
	Start Position
	End   Position
}

// IsZero reports whether a span has no source position.
func (s Span) IsZero() bool {
	return s.Start.Line == 0 || s.Start.Column == 0
}

// Node is implemented by every AST node.
type Node interface {
	String() string
}

// Statement is implemented by nodes that can appear as statements.
type Statement interface {
	Node
	statementNode()
}

// Expression is implemented by nodes that produce a value.
type Expression interface {
	Node
	expressionNode()
}

// Program is the root AST node for a Kizu source file.
type Program struct {
	Decls []Decl
}

// ImportDecl represents one explicit top-level module import.
type ImportDecl struct {
	Path []string
}

// declNode marks ImportDecl as a declaration node.
func (*ImportDecl) declNode() {}

// String returns a compact debug representation of the import declaration.
func (d *ImportDecl) String() string {
	return "import " + strings.Join(d.Path, "::")
}

// Decl is implemented by top-level declarations.
type Decl interface {
	Node
	declNode()
}

// String returns a compact debug representation of the program.
func (p *Program) String() string {
	var out bytes.Buffer
	for i, decl := range p.Decls {
		if i > 0 {
			out.WriteByte('\n')
		}
		out.WriteString(decl.String())
	}
	return out.String()
}

// FunctionSignature is everything a caller is promised: the declaration without
// its body or its doc comment.
//
// It is a type of its own so that the code deciding what a call site sees
// cannot reach the body. A signature that came from a body is a signature no
// other package can be told without being shipped the body, and the shape of
// the compiler follows from that: a package is described to another package by
// this, and only generic and comptime bodies travel with it because
// instantiation reruns them.
type FunctionSignature struct {
	// Receiver reports whether Params[0] is the value this function is a method
	// on. A method is filed under its receiver's type rather than in its module,
	// so two types in one module may each have a `len`.
	Receiver bool
	Name     string
	// StaticParams is the `<...>` list. An entry with no declared type is a
	// type parameter; one with a type is a compile-time value. Both are
	// compile-time, which is why they live here and not in Params.
	StaticParams   []StaticParam
	Params         []Param
	ReturnType     typ.Type
	ReturnBorrow   string
	RequiresUnsafe bool
	ExternABI      string
	Public         bool
	Std            bool
}

// FunctionDecl represents a function declaration.
type FunctionDecl struct {
	FunctionSignature
	Doc  string
	Body *BlockStmt
	// FieldsBody marks a `deinit() -> void = fields;` declaration whose body is
	// generated by ExpandFieldsDeinit before any checker reads it (ADR-0091).
	FieldsBody bool
}

// StaticParam is one entry of a `<...>` static argument list.
type StaticParam struct {
	Name string
	// Type is absent for a type parameter, and names the value's type for a
	// compile-time value such as `<n: i64>` or `<worker: Function>`.
	Type typ.Type
}

// IsType reports whether this entry declares a type parameter.
func (p StaticParam) IsType() bool { return p.Type == nil }

// String renders the parameter as it is written in source.
func (p StaticParam) String() string {
	if p.IsType() {
		return p.Name
	}
	return p.Name + ": " + p.Type.String()
}

// TypeParamNames returns the names of the entries that declare types.
func (s *FunctionSignature) TypeParamNames() []string {
	names := []string{}
	for _, param := range s.StaticParams {
		if param.IsType() {
			names = append(names, param.Name)
		}
	}
	return names
}

// declNode marks FunctionDecl as a declaration node.
func (*FunctionDecl) declNode() {}

// String returns a compact debug representation of the function.
func (d *FunctionDecl) String() string {
	receiver := ""
	rest := d.Params
	if d.Receiver && len(rest) > 0 {
		receiver = "(" + rest[0].String() + ") "
		rest = rest[1:]
	}
	params := make([]string, 0, len(rest))
	for _, p := range rest {
		params = append(params, p.String())
	}
	ret := ""
	if d.ReturnType != nil {
		ret = " -> " + d.ReturnType.String()
		if d.ReturnBorrow != "" {
			ret += " borrows " + d.ReturnBorrow
		}
	}
	typeParams := staticParamText(d.StaticParams)
	if typeParams != "" {
		typeParams = "<" + typeParams + ">"
	}
	prefix := ""
	if d.Public {
		prefix += "pub "
	}
	if d.RequiresUnsafe {
		prefix += "unsafe "
	}
	if d.ExternABI != "" {
		return fmt.Sprintf("%sextern %q fn %s%s%s(%s)%s",
			prefix, d.ExternABI, receiver, d.Name, typeParams, strings.Join(params, ", "), ret)
	}
	if d.Body == nil {
		return fmt.Sprintf("%sfn %s%s%s(%s)%s;",
			prefix, receiver, d.Name, typeParams, strings.Join(params, ", "), ret)
	}
	return fmt.Sprintf("%sfn %s%s%s(%s)%s %s",
		prefix, receiver, d.Name, typeParams, strings.Join(params, ", "), ret, d.Body.String())
}

// TestDecl represents a top-level test block.
type TestDecl struct {
	Name string
	Body *BlockStmt
}

// declNode marks TestDecl as a declaration node.
func (*TestDecl) declNode() {}

// String returns a compact debug representation of the test declaration.
func (d *TestDecl) String() string {
	if d.Body == nil {
		return fmt.Sprintf("test %q <missing>", d.Name)
	}
	return fmt.Sprintf("test %q %s", d.Name, d.Body.String())
}

// StructDecl represents a top-level struct declaration.
type StructDecl struct {
	Name       string
	Doc        string
	TypeParams []string
	Fields     []Field
	Public     bool
	// RequiresUnsafe marks a struct whose fields carry an invariant the
	// compiler cannot check, spelled `unsafe struct`. Establishing or changing
	// that invariant is what needs `unsafe`, so writes are marked and reads are
	// not.
	RequiresUnsafe bool
}

// declNode marks StructDecl as a declaration node.
func (*StructDecl) declNode() {}

// String returns a compact debug representation of the struct declaration.
func (d *StructDecl) String() string {
	fields := make([]string, 0, len(d.Fields))
	for _, field := range d.Fields {
		fields = append(fields, field.String())
	}
	prefix := ""
	if d.Public {
		prefix = "pub "
	}
	if d.RequiresUnsafe {
		prefix += "unsafe "
	}
	typeParams := typeParamText(d.TypeParams)
	if typeParams != "" {
		typeParams = "<" + typeParams + ">"
	}
	return fmt.Sprintf("%sstruct %s%s { %s }",
		prefix, d.Name, typeParams, strings.Join(fields, ", "))
}

